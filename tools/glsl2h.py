#!/usr/bin/env python3
# Embeds every .glsl under shaders/ into src64/ps_glsl_embedded.h (built-in fallback + "write default shaders" in the menu).
import os, sys
root, out = sys.argv[1], sys.argv[2]
items = []
for d, _, fs in os.walk(root):
    for f in sorted(fs):
        if f.endswith('.glsl'):
            p = os.path.join(d, f); rel = os.path.relpath(p, root).replace(os.sep, '/')
            items.append((rel, open(p, encoding='utf-8').read()))
items.sort()
with open(out, 'w', encoding='utf-8') as o:
    o.write('// GENERATED by tools/glsl2h.py from shaders/ - edit the .glsl files, not this header\n#pragma once\n')
    o.write('struct PSEmbeddedGlsl { const char* path; const char* text; };\nstatic const PSEmbeddedGlsl kEmbeddedGlsl[] = {\n')
    for rel, txt in items:
        o.write('  { "%s", R"PGFXGLSL(%s)PGFXGLSL" },\n' % (rel, txt))
    o.write('};\nstatic const int kEmbeddedGlslCount = %d;\n' % len(items))
print('glsl2h: %d files -> %s' % (len(items), out))
